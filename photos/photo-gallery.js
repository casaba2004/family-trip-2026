/* 관광지 사진 갤러리: 좌우 스와이프는 브라우저 기본 스크롤 사용 */
function escapePhotoText(value){
  return String(value).replace(/[&<>"']/g, c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
}
function renderTourGallery(name){
  const photos=TOUR_PHOTOS[name];
  if(!photos || !photos.length) return '';
  return `<section class="tour-gallery" aria-label="${escapePhotoText(name)} 사진">
    <div class="tour-gallery-stage">
      <div class="tour-gallery-track" tabindex="0" aria-label="관광지 사진, 좌우로 넘겨보기">
        ${photos.map((photo,i)=>`<figure class="tour-gallery-slide" aria-label="${i+1} / ${photos.length}">
          <div class="tour-gallery-image"><img src="${escapePhotoText(photo.src)}" alt="${escapePhotoText(photo.caption)}" width="${photo.width}" height="${photo.height}" loading="${i===0?'eager':'lazy'}" decoding="async" onerror="showTourPhotoError(this)"></div>
          <figcaption>${escapePhotoText(photo.caption)}</figcaption>
        </figure>`).join('')}
      </div>
      <button class="tour-gallery-nav tour-gallery-prev" type="button" data-photo-step="-1" aria-label="이전 사진">‹</button>
      <button class="tour-gallery-nav tour-gallery-next" type="button" data-photo-step="1" aria-label="다음 사진">›</button>
      <span class="tour-gallery-count" aria-live="polite" aria-atomic="true">1 / ${photos.length}</span>
    </div>
    <p class="tour-gallery-hint">사진을 좌우로 밀어 넘겨보세요.</p>
    <details class="tour-gallery-credits"><summary>사진 출처 · 이용조건</summary><ol>
      ${photos.map(photo=>`<li>${escapePhotoText(photo.caption)}<br><a href="${escapePhotoText(photo.source)}" target="_blank" rel="noopener noreferrer">${escapePhotoText(photo.credit)} · 출처</a> · <a href="${escapePhotoText(photo.licenseUrl)}" target="_blank" rel="noopener noreferrer">${escapePhotoText(photo.license)}</a><br>${escapePhotoText(photo.changes)}</li>`).join('')}
    </ol></details>
  </section>`;
}
function showTourPhotoError(img){
  const parent=img.parentElement;
  if(!parent) return;
  const note=document.createElement('span');
  note.className='tour-gallery-error';
  note.textContent='사진을 불러오지 못했어요. 아래 사진 출처에서 확인하실 수 있어요.';
  parent.replaceChildren(note);
}
function initTourGallery(){
  const gallery=document.querySelector('#sheetBody .tour-gallery');
  if(!gallery) return;
  const track=gallery.querySelector('.tour-gallery-track');
  const count=gallery.querySelector('.tour-gallery-count');
  const total=track.children.length;
  let current=0;
  function sync(){
    if(track.clientWidth>0) current=Math.max(0,Math.min(total-1,Math.round(track.scrollLeft/track.clientWidth)));
    count.textContent=`${current+1} / ${total}`;
  }
  function step(delta){
    if(!track.clientWidth) return;
    current=(current+delta+total)%total;
    // 즉시 이동하여 빠른 연속 터치도 한 장씩 정확하게 반영합니다.
    track.scrollTo({left:current*track.clientWidth,behavior:'instant'});
    count.textContent=`${current+1} / ${total}`;
  }
  track.addEventListener('scroll',sync,{passive:true});
  gallery.querySelectorAll('[data-photo-step]').forEach(button=>{
    button.addEventListener('click',()=>step(Number(button.dataset.photoStep)));
  });
  track.addEventListener('keydown',event=>{
    if(event.key==='ArrowLeft' || event.key==='ArrowRight'){
      event.preventDefault();step(event.key==='ArrowRight'?1:-1);
    }
  });
}

